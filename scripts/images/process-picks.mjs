// Turns reviewed picks into project images, seed photo refs and the credits file.
// Usage: node scripts/images/process-picks.mjs <candidatesDir1> <candidatesDir2>
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import sharp from 'sharp';

const dirs = { 1: process.argv[2], 2: process.argv[3] };
const manifests = {};
for (const [k, d] of Object.entries(dirs)) manifests[k] = JSON.parse(await readFile(join(d, 'manifest.json'), 'utf8'));
const picks = JSON.parse(await readFile(new URL('./picks.json', import.meta.url), 'utf8'));

const refs = {};
const credits = [];
for (const [name, [round, key, index, alt]] of Object.entries(picks)) {
  const c = manifests[round][key].find((x) => x.i === index);
  if (!c) throw new Error(`missing candidate ${name}`);
  const src = `/images/${name}.jpg`;
  const out = join('public', src);
  await mkdir(dirname(out), { recursive: true });
  // House grade: slightly lowered saturation, same for every image. Metadata is stripped by default.
  const image = sharp(c.file).rotate().resize({ width: 1200, withoutEnlargement: true }).modulate({ saturation: 0.94 });
  const { width, height } = await image.jpeg({ quality: 74, mozjpeg: true }).toFile(out);
  const blur = await sharp(c.file).resize(16, 12, { fit: 'cover' }).webp({ quality: 40 }).toBuffer();
  refs[name] = { src, alt, width, height };
  credits.push({
    src, alt, blurDataURL: `data:image/webp;base64,${blur.toString('base64')}`,
    source: 'Wikimedia Commons', page: c.page, author: c.author || 'Unknown', licence: c.licence, fetched: '2026-11-15',
  });
}

const header = '// Generated by scripts/images/process-picks.mjs. Do not edit by hand.\n';
await writeFile(
  'src/data/seed/photos.ts',
  `${header}import type { ImageRef } from '@/domain/types';\n\nexport const PHOTOS = ${JSON.stringify(refs, null, 2)} as const satisfies Record<string, ImageRef>;\n\nexport type PhotoKey = keyof typeof PHOTOS;\n`,
);
await writeFile(
  'src/content/image-credits.ts',
  `${header}export interface ImageCredit {\n  src: string; alt: string; blurDataURL: string;\n  source: string; page: string; author: string; licence: string; fetched: string;\n}\n\nexport const IMAGE_CREDITS: ImageCredit[] = ${JSON.stringify(credits, null, 2)};\n\nconst BY_SRC = new Map(IMAGE_CREDITS.map((c) => [c.src, c]));\nexport const blurFor = (src: string): string | undefined => BY_SRC.get(src)?.blurDataURL;\n`,
);
console.log(credits.length, 'images');
